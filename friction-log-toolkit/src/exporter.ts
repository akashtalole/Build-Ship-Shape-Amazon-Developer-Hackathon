import type { LogEntry, LogFile } from "./types.js";
import { clusterByTheme, overlaps, profileOfText } from "./cluster.js";
import type { AggregateReport } from "./aggregate.js";

export type ExportFormat = "md" | "json" | "txt" | "timeline";

export function formatTimestamp(iso: string): string {
  // Keep it simple and readable: "2026-09-02 14:31 UTC"
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  return d.toISOString().replace("T", " ").replace(/\.\d+Z$/, " UTC");
}

function renderBullets(entries: LogEntry[]): string[] {
  return entries.map((e) => `- ${e.note} _(${formatTimestamp(e.timestamp)})_`);
}

function renderNumbered(entries: LogEntry[]): string[] {
  return entries.map(
    (e, i) => `${i + 1}. ${e.note} _(${formatTimestamp(e.timestamp)})_`
  );
}

function renderPlainBullets(entries: LogEntry[]): string[] {
  return entries.map((e) => `- ${e.note} (${formatTimestamp(e.timestamp)})`);
}

function renderPlainNumbered(entries: LogEntry[]): string[] {
  return entries.map(
    (e, i) => `${i + 1}. ${e.note} (${formatTimestamp(e.timestamp)})`
  );
}

function groupByWellKnownTag(log: LogFile): {
  worked: LogEntry[];
  friction: LogEntry[];
  featureRequests: LogEntry[];
  other: LogEntry[];
} {
  const worked = log.entries.filter((e) => e.tag === "worked-well");
  const friction = log.entries.filter((e) => e.tag === "friction");
  const featureRequests = log.entries.filter((e) => e.tag === "feature-request");
  const known = new Set(["worked-well", "friction", "feature-request"]);
  const other = log.entries.filter((e) => !known.has(e.tag));
  return { worked, friction, featureRequests, other };
}

export interface ExportOptions {
  title?: string;
}

/**
 * Turns a LogFile into a Markdown report matching the structure real
 * hackathon FRICTION_LOG.md submissions use: "What worked well",
 * "Friction encountered" (numbered, since these are the meat of the
 * submission's friction-log bonus), "Feature requests", and a catch-all
 * "Other notes" for anything tagged differently (or not tagged at all).
 */
export function exportMarkdown(log: LogFile, options: ExportOptions = {}): string {
  const title = options.title ?? "Friction Log";
  const { worked, friction, featureRequests, other } = groupByWellKnownTag(log);

  const lines: string[] = [];
  lines.push(`# ${title}`);
  lines.push("");
  lines.push(
    `_Generated by [friction-log-toolkit](https://github.com/) on ${formatTimestamp(
      new Date().toISOString()
    )}. ${log.entries.length} entr${log.entries.length === 1 ? "y" : "ies"} logged since ${formatTimestamp(log.createdAt)}._`
  );
  lines.push("");

  lines.push("## What worked well");
  lines.push("");
  if (worked.length === 0) {
    lines.push("_No entries logged yet — run `friction-log add \"...\" --tag worked-well` to add one._");
  } else {
    lines.push(...renderBullets(worked));
  }
  lines.push("");

  lines.push("## Friction encountered");
  lines.push("");
  if (friction.length === 0) {
    lines.push("_No entries logged yet — run `friction-log add \"...\" --tag friction` to add one._");
  } else {
    lines.push(...renderNumbered(friction));
  }
  lines.push("");

  lines.push("## Feature requests");
  lines.push("");
  if (featureRequests.length === 0) {
    lines.push("_No entries logged yet — run `friction-log add \"...\" --tag feature-request` to add one._");
  } else {
    lines.push(...renderBullets(featureRequests));
  }
  lines.push("");

  lines.push("## Other notes");
  lines.push("");
  if (other.length === 0) {
    lines.push("_Nothing untagged or custom-tagged yet._");
  } else {
    lines.push(
      ...other.map(
        (e) => `- **[${e.tag}]** ${e.note} _(${formatTimestamp(e.timestamp)})_`
      )
    );
  }
  lines.push("");

  return lines.join("\n");
}

/**
 * Same grouped sections as `exportMarkdown`, rendered as plain text (no `#`
 * headings, no `_..._` emphasis, no `**bold**`) — for pasting into places
 * that don't render Markdown, e.g. a Slack message or a plain log file.
 */
export function exportText(log: LogFile, options: ExportOptions = {}): string {
  const title = options.title ?? "Friction Log";
  const { worked, friction, featureRequests, other } = groupByWellKnownTag(log);

  const lines: string[] = [];
  lines.push(title);
  lines.push("=".repeat(title.length));
  lines.push("");
  lines.push(
    `Generated by friction-log-toolkit on ${formatTimestamp(
      new Date().toISOString()
    )}. ${log.entries.length} entr${log.entries.length === 1 ? "y" : "ies"} logged since ${formatTimestamp(log.createdAt)}.`
  );
  lines.push("");

  lines.push("WHAT WORKED WELL");
  lines.push("-".repeat(16));
  if (worked.length === 0) {
    lines.push("No entries logged yet.");
  } else {
    lines.push(...renderPlainBullets(worked));
  }
  lines.push("");

  lines.push("FRICTION ENCOUNTERED");
  lines.push("-".repeat(20));
  if (friction.length === 0) {
    lines.push("No entries logged yet.");
  } else {
    lines.push(...renderPlainNumbered(friction));
  }
  lines.push("");

  lines.push("FEATURE REQUESTS");
  lines.push("-".repeat(16));
  if (featureRequests.length === 0) {
    lines.push("No entries logged yet.");
  } else {
    lines.push(...renderPlainBullets(featureRequests));
  }
  lines.push("");

  lines.push("OTHER NOTES");
  lines.push("-".repeat(11));
  if (other.length === 0) {
    lines.push("Nothing untagged or custom-tagged yet.");
  } else {
    lines.push(
      ...other.map(
        (e) => `- [${e.tag}] ${e.note} (${formatTimestamp(e.timestamp)})`
      )
    );
  }
  lines.push("");

  return lines.join("\n");
}

/** Raw structured entries as JSON — for scripting/CI integration. */
export function exportJson(log: LogFile): string {
  return JSON.stringify(log.entries, null, 2) + "\n";
}

// --- Narrative timeline export ---------------------------------------------

function runLengthGroups(entries: LogEntry[]): LogEntry[][] {
  const groups: LogEntry[][] = [];
  for (const e of entries) {
    const last = groups[groups.length - 1];
    if (last && last[last.length - 1].tag === e.tag) {
      last.push(e);
    } else {
      groups.push([e]);
    }
  }
  return groups;
}

/** Divides the log into thirds by position (not wall-clock time) — "Early on" / "Partway through" / "Later on" — a simple, deterministic stand-in for "where in the story is this." */
function phaseFor(startIndex: number, total: number): string {
  if (total <= 1) return "";
  const ratio = startIndex / (total - 1);
  if (ratio < 1 / 3) return "Early on";
  if (ratio < 2 / 3) return "Partway through";
  return "Later on";
}

/**
 * Lowercases a note's first letter so it reads naturally mid-sentence
 * ("...came up: docs were unclear" not "...came up: Docs were unclear") —
 * except when the note starts with an acronym (two or more capitals in a
 * row, e.g. "MCP schema..." or "OAuth sandbox..."), which stays as-is rather
 * than becoming the garbled "mCP schema..."/"oAuth sandbox...".
 */
function lowerFirst(s: string): string {
  if (s.length === 0) return s;
  if (s.length >= 2 && /[A-Z]/.test(s[0]) && /[A-Z]/.test(s[1])) return s;
  return s[0].toLowerCase() + s.slice(1);
}

function capitalize(s: string): string {
  return s.length === 0 ? s : s[0].toUpperCase() + s.slice(1);
}

/** Joins 1+ notes into a flowing clause: "X" / "first X, then Y" / "first X, then Y, and again Z". */
function narrateList(notes: string[]): string {
  if (notes.length === 1) return lowerFirst(notes[0]);
  if (notes.length === 2) return `first ${lowerFirst(notes[0])}, then ${lowerFirst(notes[1])}`;
  const middle = notes.slice(1, -1).map((n) => `then ${lowerFirst(n)}`);
  return [`first ${lowerFirst(notes[0])}`, ...middle, `and again ${lowerFirst(notes[notes.length - 1])}`].join(", ");
}

function sentence(connector: string, body: string): string {
  return connector ? `${connector}, ${body}.` : `${capitalize(body)}.`;
}

/**
 * Turns a LogFile into chronological narrative prose instead of a bulleted
 * list — consecutive entries that share a tag are folded into one paragraph
 * ("friction showed up more than once: first X, then Y") rather than
 * repeating a template per entry, and a `worked-well` paragraph that shares
 * significant wording with an earlier `friction` paragraph (via the same
 * theme-overlap check `aggregate`'s clustering uses) is phrased as a
 * resolution ("this was resolved: ...") instead of a generic "went smoothly"
 * note.
 *
 * Entirely template-based and deterministic — no LLM call, so the same log
 * always produces the exact same prose, in the same spirit as
 * `bee-studyloop`'s `TemplateFlashcardGenerator`. Written to be pasted
 * directly into a Devpost-style "challenges we ran into" section.
 */
export function exportTimeline(log: LogFile, options: ExportOptions = {}): string {
  const title = options.title ?? "Friction Log";
  const sorted = [...log.entries].sort((a, b) => a.timestamp.localeCompare(b.timestamp));

  const lines: string[] = [];
  lines.push(`# ${title} — Timeline`);
  lines.push("");
  if (sorted.length === 0) {
    lines.push("_No entries logged yet — nothing to narrate._");
    return lines.join("\n") + "\n";
  }
  lines.push(
    `_A chronological narrative of ${sorted.length} entr${sorted.length === 1 ? "y" : "ies"} logged between ${formatTimestamp(
      sorted[0].timestamp
    )} and ${formatTimestamp(
      sorted[sorted.length - 1].timestamp
    )}, generated by friction-log-toolkit — paste this into a write-up's "challenges we ran into" section._`
  );
  lines.push("");

  const groups = runLengthGroups(sorted);
  const priorFrictionGroups: LogEntry[][] = [];
  let lastPhase: string | null = null;
  let globalIndex = 0;

  for (const group of groups) {
    const phase = phaseFor(globalIndex, sorted.length);
    const connector = phase !== "" && phase === lastPhase ? "Then" : phase;
    if (phase !== "") lastPhase = phase;
    const notes = group.map((e) => e.note);
    const tag = group[0].tag;

    let paragraph: string;
    if (tag === "friction") {
      paragraph =
        notes.length === 1
          ? sentence(connector, notes[0])
          : sentence(connector, `friction showed up more than once: ${narrateList(notes)}`);
      priorFrictionGroups.push(group);
    } else if (tag === "worked-well") {
      const groupProfile = profileOfText(notes.join(" "));
      const resolvesEarlierFriction = priorFrictionGroups.some((fg) =>
        overlaps(groupProfile, profileOfText(fg.map((e) => e.note).join(" ")))
      );
      if (resolvesEarlierFriction) {
        paragraph = sentence(connector, `this was resolved: ${narrateList(notes)}`);
      } else {
        paragraph =
          notes.length === 1
            ? sentence(connector, `${lowerFirst(notes[0])} — a welcome bit of smooth sailing`)
            : sentence(connector, `several things went smoothly: ${narrateList(notes)}`);
      }
    } else if (tag === "feature-request") {
      paragraph =
        notes.length === 1
          ? sentence(connector, `the team noted a feature request: ${lowerFirst(notes[0])}`)
          : sentence(connector, `a few feature requests came up: ${narrateList(notes)}`);
    } else {
      paragraph =
        notes.length === 1
          ? sentence(connector, `worth noting, ${lowerFirst(notes[0])}`)
          : sentence(connector, `a handful of other notes came up: ${narrateList(notes)}`);
    }

    lines.push(paragraph);
    lines.push("");
    globalIndex += group.length;
  }

  return lines.join("\n");
}

// --- GitHub issue export (local files only — no API calls) -----------------

export interface GithubIssueFile {
  filename: string;
  title: string;
  body: string;
}

function slugify(s: string): string {
  const slug = s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60);
  return slug.length > 0 ? slug : "entry";
}

/** A short (<=4 letter) theme word is likely one of `cluster.ts`'s acronyms (e.g. "mcp") — upper-case it entirely rather than just its first letter, so a theme label reads "MCP Schema" instead of "Mcp Schema". */
function titleCase(commaJoinedWords: string): string {
  return commaJoinedWords
    .split(/,\s*/)
    .slice(0, 5)
    .join(" ")
    .split(/\s+/)
    .filter((w) => w.length > 0)
    .map((w) => (w.length <= 4 ? w.toUpperCase() : w[0].toUpperCase() + w.slice(1)))
    .join(" ");
}

/**
 * Formats every actionable entry (everything except `worked-well`, which
 * isn't a problem to file) as ready-to-file GitHub issue bodies — one file
 * per theme cluster (via `clusterByTheme`, so several entries about the same
 * root problem become one issue instead of a flood of near-duplicates), in
 * the same "what happened" framing `exportMarkdown`'s "Friction encountered"
 * section already uses.
 *
 * **This is local-file export only.** Nothing here calls the GitHub API or
 * needs a token — the caller reviews the generated files and files them
 * themselves, e.g. `gh issue create -R <owner/repo> --title "..." --body-file <file>`,
 * or pastes the content into the GitHub UI.
 */
export function exportGithubIssues(log: LogFile, repo: string): GithubIssueFile[] {
  const actionable = log.entries.filter((e) => e.tag !== "worked-well");
  if (actionable.length === 0) return [];
  const clusters = clusterByTheme(actionable);

  return clusters.map((cluster, i) => {
    const label = titleCase(cluster.theme);
    const title = `[friction-log] ${label}`;
    const bodyLines: string[] = [];
    bodyLines.push(
      `> Suggested target repository: **${repo}**. This file was generated locally by friction-log-toolkit — it was **not** filed on GitHub automatically. Review it, then run:`
    );
    bodyLines.push(">");
    bodyLines.push(`> \`gh issue create -R ${repo} --title "${title.replace(/"/g, '\\"')}" --body-file <this-file>\``);
    bodyLines.push(">");
    bodyLines.push("> ...or paste this content into the GitHub UI yourself.");
    bodyLines.push("");
    bodyLines.push("## What happened");
    bodyLines.push("");
    cluster.entries.forEach((e, idx) => {
      const gitSuffix = e.gitBranch ? ` (branch \`${e.gitBranch}\`, commit \`${e.gitCommit}\`)` : "";
      bodyLines.push(`${idx + 1}. **[${e.tag}]** ${e.note} _(${formatTimestamp(e.timestamp)})_${gitSuffix}`);
    });
    bodyLines.push("");
    bodyLines.push("## Suggested labels");
    bodyLines.push("");
    bodyLines.push(`\`friction-log\`, \`${cluster.dominantTag}\``);
    bodyLines.push("");

    const filename = `${String(i + 1).padStart(3, "0")}-${slugify(label)}.md`;
    return { filename, title, body: bodyLines.join("\n") };
  });
}

// --- Team aggregation report -------------------------------------------------

/**
 * Renders an `aggregate` result as a Markdown report grouped by theme
 * cluster (largest theme first) instead of one flat list per teammate —
 * the whole point of `aggregate` over just concatenating everyone's export.
 */
export function formatAggregateReport(report: AggregateReport, options: ExportOptions = {}): string {
  const title = options.title ?? "Team Friction Log — Aggregated";
  const lines: string[] = [];
  lines.push(`# ${title}`);
  lines.push("");
  lines.push(
    `_Aggregated from ${report.sources.length} source${report.sources.length === 1 ? "" : "s"} (${report.sources.join(
      ", "
    )}) — ${report.totalEntries} entr${report.totalEntries === 1 ? "y" : "ies"} after de-duplication${
      report.duplicatesAcrossSources > 0 ? ` (${report.duplicatesAcrossSources} duplicate id(s) skipped)` : ""
    }, grouped into ${report.clusters.length} theme${report.clusters.length === 1 ? "" : "s"}._`
  );
  lines.push("");

  if (report.sourceErrors.length > 0) {
    lines.push("## Unreachable sources");
    lines.push("");
    for (const se of report.sourceErrors) {
      lines.push(`- ${se.url}: ${se.error}`);
    }
    lines.push("");
  }

  if (report.clusters.length === 0) {
    lines.push("_No entries were pulled from any reachable source._");
    lines.push("");
    return lines.join("\n");
  }

  lines.push("## Themes");
  lines.push("");
  report.clusters.forEach((cluster, i) => {
    lines.push(
      `### ${i + 1}. ${cluster.theme} _(${cluster.entries.length} entr${
        cluster.entries.length === 1 ? "y" : "ies"
      }, mostly "${cluster.dominantTag}")_`
    );
    lines.push("");
    for (const e of cluster.entries) {
      const gitSuffix = e.gitBranch ? ` [${e.gitBranch}@${e.gitCommit}]` : "";
      lines.push(`- **[${e.tag}]** ${e.note} _(${formatTimestamp(e.timestamp)})_${gitSuffix}`);
    }
    lines.push("");
  });

  return lines.join("\n");
}
